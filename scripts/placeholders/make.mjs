// Writes src/styles/placeholders.css: a tiny blurred copy of each image below, as a CSS variable (--lqip-<name>),
// shown while the image itself loads (src/styles/placeholders-use.css, the script in BaseLayout.astro).
// Run it again after changing one of these images:  node scripts/placeholders/make.mjs
// Uses sharp, which Astro installs.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = new URL("../../", import.meta.url);
const IMAGES = [
  // Stickers (transparent): the placeholder is their blurred silhouette.
  "elf-2.webp",
  "santa-1.webp",
  "santa-2.webp",
  "santa-3.webp",
  // Full-bleed photos (background-size: cover): same proportions, so the placeholder lines up under the photo.
  "login-garage-door.webp",
  "login-garage-door-portrait.webp",
  "welcome.jpg",
  "enter-background.jpg",
  "not-found.jpg",
  "party-garage-door-3.jpg",
  "rolled-envelopes.jpg",
];

const lines = [];
for (const file of IMAGES) {
  // 32px on the long side, keeping the proportions (and transparency), blurred here: not with a CSS filter, which
  // would blur the page over a photo, and under which Chrome measures the elf's first paint too small for LCP.
  const data = await sharp(fileURLToPath(new URL(`public/${file}`, root)))
    .resize(32, 32, { fit: "inside" })
    .blur(1.2)
    .webp({ quality: 60, alphaQuality: 60 })
    .toBuffer();
  const name = file.replace(/\.[a-z]+$/, "");
  lines.push(`  --lqip-${name}: url("data:image/webp;base64,${data.toString("base64")}");`);
}

writeFileSync(new URL("src/styles/placeholders.css", root), `/* Generated by scripts/placeholders/make.mjs: tiny blurred copies of images, shown while they load. Don't edit. */

:root {
${lines.join("\n")}
}
`);
console.log(`wrote ${IMAGES.length} placeholders`);
