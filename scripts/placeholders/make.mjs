// Writes src/styles/placeholders.css: a blurred copy of each image below, as a CSS variable (--lqip-<name>), shown
// while the image itself loads (src/styles/placeholders-use.css, the script in index.astro).
// Each copy is the image's ThumbHash (https://evanw.github.io/thumbhash/, keeps transparency) decoded here, at build
// time, into a small WebP: the page shows it straight from the CSS, with no decoder to load first.
// Run it again after changing one of these images:  node scripts/placeholders/make.mjs
// Uses thumbhash (a dev dependency) and sharp, which Astro installs.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { rgbaToThumbHash, thumbHashToRGBA } from "thumbhash";

const root = new URL("../../", import.meta.url);
const IMAGES = [
  // Stickers (transparent): the placeholder is their blurred silhouette.
  "elf-2.webp",
  "santa-1.webp",
  "santa-2.webp",
  "santa-3.webp",
  // Full-bleed photos (background-size: cover): same proportions, so the placeholder lines up under the photo.
  "login-garage-door.webp",
  "login-garage-door-portrait.webp",
  "welcome.jpg",
  "enter-background.jpg",
  "not-found.jpg",
  "party-garage-door-3.jpg",
  "rolled-envelopes.jpg",
];

/** A sticker's decoded transparency doesn't quite reach zero at the borders: fade it out there, or it shows as a box. */
const featherEdges = ({ w, h, rgba }, width = 5) => {
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const edge = Math.min(x, y, w - 1 - x, h - 1 - y);
      if (edge < width) rgba[(y * w + x) * 4 + 3] *= edge / width;
    }
  }
};

const lines = [];
for (const file of IMAGES) {
  const sticker = (await sharp(fileURLToPath(new URL(`public/${file}`, root))).metadata()).hasAlpha;

  // ThumbHash takes at most 100x100: the image shrunk to that, keeping its proportions.
  const { data: pixels, info } = await sharp(fileURLToPath(new URL(`public/${file}`, root)))
    .resize(100, 100, { fit: "inside" })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const hash = rgbaToThumbHash(info.width, info.height, pixels);

  // Decoded back: a smooth ~32px image (already blurred, so no CSS filter, which would blur the page over a photo
  // and make Chrome measure the elf's first paint too small for LCP), stored as a WebP.
  const thumb = thumbHashToRGBA(hash);
  if (sticker) featherEdges(thumb);
  const data = await sharp(Buffer.from(thumb.rgba), { raw: { width: thumb.w, height: thumb.h, channels: 4 } })
    .webp({ quality: 70, alphaQuality: 70 })
    .toBuffer();

  const name = file.replace(/\.[a-z]+$/, "");
  console.log(`${name.padEnd(32)} ThumbHash ${Buffer.from(hash).toString("base64")}  ${thumb.w}x${thumb.h}  ${data.length} B`);
  lines.push(`  --lqip-${name}: url("data:image/webp;base64,${data.toString("base64")}");`);
}

writeFileSync(new URL("src/styles/placeholders.css", root), `/* Generated by scripts/placeholders/make.mjs: each image's ThumbHash, decoded, shown while it loads. Don't edit. */

:root {
${lines.join("\n")}
}
`);
console.log(`wrote ${IMAGES.length} placeholders`);
